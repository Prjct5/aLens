#!/bin/sh
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOSQL
CREATE ROLE mlflow LOGIN PASSWORD '${MLFLOW_DB_PASSWORD}';
CREATE DATABASE mlflow OWNER mlflow;
CREATE ROLE pipeline LOGIN PASSWORD '${PIPELINE_PASSWORD}';
CREATE ROLE api_ro LOGIN PASSWORD '${API_RO_PASSWORD}';
CREATE ROLE dashboard_ro LOGIN PASSWORD '${DASHBOARD_RO_PASSWORD}';
GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO pipeline, api_ro, dashboard_ro;
EOSQL
